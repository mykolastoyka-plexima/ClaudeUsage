const DICTS: Record<Lang, Dict> = { cs, en, uk, de, fr, es, it, pl };

let current: Lang = "en";
let currentLocale = "en-US";

export function setLanguage(lang: string, locale: string): void {
  current = (LANGS as readonly string[]).includes(lang) ? (lang as Lang) : "en";
  currentLocale = locale || "en-US";
  document.documentElement.lang = current;
}

export function lang(): Lang {
  return current;
}

/** BCP 47 locale for Intl formatting (dates, numbers, relative time). */
export function locale(): string {
  return currentLocale;
}

export function t(key: Key, params?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Localised label of a limit from its kind (labels are not sent by the backend). */
export function limitLabel(kind: string, name: string | null): string {
  if (kind === "session") return t("session");
  if (kind === "weekly_all") return t("weekly");
  return t("weeklyModel", { name: name ?? kind });
}

/** Backend error codes ("offline", "timeout", "format", "http:503") to text. */
export function errorText(code: string | null): string {
  if (!code || code === "offline") return t("errOffline");
  if (code === "timeout") return t("errTimeout");
  if (code === "format") return t("errFormat");
  if (code.startsWith("http:")) return t("errHttp", { code: code.slice(5) });
  return code;
}
